"""GGUF export: the Modelfile and the order of merge, convert and ``ollama create``.

No training library, llama.cpp checkout or Ollama server is needed: the three heavy steps
are replaced by recorders, and the base model's Modelfile is a fixed text.
"""

from __future__ import annotations

import json

import pytest

from bist_harness.finetune import export as fx

# what `ollama show qwen3.5:0.8b --modelfile` prints (licence cut): a built-in renderer
BASE_RENDERER = """# Modelfile generated by "ollama show"
# To build a new Modelfile based on this, replace FROM with:
# FROM qwen3.5:0.8b

FROM C:\\Users\\someone\\.ollama\\models\\blobs\\sha256-889e
DRAFT C:\\Users\\someone\\.ollama\\models\\blobs\\sha256-b010
TEMPLATE {{ .Prompt }}
RENDERER qwen3.5
PARSER qwen3.5
PARAMETER draft_num_predict 2
PARAMETER presence_penalty 1.5
PARAMETER temperature 1
PARAMETER top_k 20
PARAMETER top_p 0.95
LICENSE \"\"\"                                 Apache License
                           Version 2.0, January 2004
\"\"\"
"""

# an older style: a Go template with a tools section and stop words
BASE_TEMPLATE = '''FROM /models/blobs/sha256-abcd
TEMPLATE """{{- if .Tools }}<|im_start|>system
# Tools
{{- range .Tools }}
{"type": "function", "function": {{ .Function }}}
{{- end }}<|im_end|>
{{ end }}{{- range .Messages }}<|im_start|>{{ .Role }}
{{ .Content }}<|im_end|>
{{ end }}<|im_start|>assistant
"""
PARAMETER stop <|im_start|>
PARAMETER stop <|im_end|>
PARAMETER temperature 0.7
'''


def test_modelfile_carries_tool_template():
    text = fx.render_modelfile("model-f16.gguf", BASE_TEMPLATE, num_ctx=6144)
    lines = text.splitlines()
    assert lines[0] == "FROM ./model-f16.gguf"
    # the base model's chat and tool template, unchanged, and its stop words
    block = BASE_TEMPLATE[
        BASE_TEMPLATE.index('TEMPLATE """') : BASE_TEMPLATE.index('"""\nPARAMETER') + 3
    ]
    assert block in text
    assert "{{- range .Tools }}" in text
    assert "PARAMETER stop <|im_start|>" in lines and "PARAMETER stop <|im_end|>" in lines
    # deterministic decoding and a context that fits the harness's longest turn
    assert "PARAMETER temperature 0" in lines
    assert "PARAMETER seed 42" in lines
    assert "PARAMETER num_ctx 6144" in lines
    assert "PARAMETER temperature 0.7" not in lines
    assert sum(line.startswith("PARAMETER temperature") for line in lines) == 1


def test_modelfile_keeps_a_built_in_renderer_and_parser():
    text = fx.render_modelfile("model.gguf", BASE_RENDERER, num_ctx=4096)
    lines = text.splitlines()
    assert "TEMPLATE {{ .Prompt }}" in lines
    assert "RENDERER qwen3.5" in lines and "PARSER qwen3.5" in lines
    # the base's sampling settings, its draft model, blobs and licence do not carry over
    for dropped in ("DRAFT", "presence_penalty", "top_k", "top_p", "temperature 1", "LICENSE"):
        assert not any(dropped in line for line in lines), dropped
    assert sum(line.startswith("FROM") for line in lines) == 1
    assert "PARAMETER temperature 0" in lines and "PARAMETER seed 42" in lines


def test_a_base_without_a_template_is_refused():
    with pytest.raises(ValueError, match="TEMPLATE"):
        fx.render_modelfile("m.gguf", "FROM x\nPARAMETER temperature 1\n", num_ctx=4096)


