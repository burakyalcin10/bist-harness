def test_export_merges_converts_and_creates_in_order(monkeypatch, tmp_path):
    adapter = tmp_path / "run" / "adapter"
    adapter.mkdir(parents=True)
    run = {"config": {"base_model": "Org/Base", "revision": "abc123"}, "max_example_tokens": 3500}
    (adapter.parent / "run.json").write_text(json.dumps(run), encoding="utf-8")
    steps = []

    def merge(adapter_dir, base_model, merged_dir, *, revision=None):
        steps.append(("merge", adapter_dir, base_model, revision))
        merged_dir.mkdir(parents=True)
        return merged_dir

    def convert(merged_dir, gguf_path, *, llama_cpp):
        steps.append(("convert", merged_dir, gguf_path.name, llama_cpp))
        gguf_path.write_bytes(b"GGUF")
        return gguf_path

    def command(args, *, cwd=None):
        steps.append(("run", list(args), cwd))
        return "" if args[1] == "create" else BASE_RENDERER

    monkeypatch.setattr(fx, "merge_adapter", merge)
    monkeypatch.setattr(fx, "convert_to_gguf", convert)
    monkeypatch.setattr(fx, "_run", command)
    out = tmp_path / "export"
    quantize = tmp_path / "bin" / "llama-quantize.exe"
    path = fx.export(
        adapter,
        "Org/Base",
        out,
        name="bist-test",
        template_from="qwen3.5:0.8b",
        llama_cpp=tmp_path / "llama.cpp",
        llama_quantize=quantize,
    )
    assert path == out / "Modelfile"
    assert [s[0] for s in steps] == ["merge", "convert", "run", "run", "run"]
    assert steps[0][2:] == ("Org/Base", "abc123")
    assert steps[1][2] == "model-f16.gguf"
    # Ollama 0.40 quantizes only safetensors imports: llama.cpp's quantizer does it
    assert steps[2][1] == [quantize, out / "model-f16.gguf", out / "model-q4_K_M.gguf", "Q4_K_M"]
    assert steps[3][1] == ["ollama", "show", "qwen3.5:0.8b", "--modelfile"]
    assert steps[4][1] == ["ollama", "create", "bist-test", "-f", "Modelfile"]
    assert steps[4][2] == out
    modelfile = path.read_text(encoding="utf-8")
    assert modelfile.startswith("FROM ./model-q4_K_M.gguf\n")
    assert "PARAMETER num_ctx 5120" in modelfile.splitlines()
    record = json.loads((out / "export.json").read_text(encoding="utf-8"))
    assert record["name"] == "bist-test" and record["quant"] == "q4_K_M"
    assert record["template_from"] == "qwen3.5:0.8b" and record["num_ctx"] == 5120


def test_export_without_quantization_keeps_f16(monkeypatch, tmp_path):
    adapter = tmp_path / "adapter"
    adapter.mkdir()
    created = []
    monkeypatch.setattr(fx, "merge_adapter", lambda a, b, m, revision=None: m)
    monkeypatch.setattr(fx, "convert_to_gguf", lambda m, g, llama_cpp: g)
    monkeypatch.setattr(fx, "_run", lambda args, cwd=None: created.append(args) or BASE_RENDERER)
    fx.export(
        adapter,
        "Org/Base",
        tmp_path / "out",
        name="bist-f16",
        quant=None,
        template_from="qwen3.5:0.8b",
        llama_cpp=tmp_path,
        num_ctx=4096,
    )
    assert len(created) == 2  # ollama show and create; no quantizer run
    assert created[-1] == ["ollama", "create", "bist-f16", "-f", "Modelfile"]
    modelfile = (tmp_path / "out" / "Modelfile").read_text(encoding="utf-8")
    assert modelfile.startswith("FROM ./model-f16.gguf\n")


